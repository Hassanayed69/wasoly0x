export function dailyDeeds(): string[] {
  const dayIndex = Math.floor(Date.now() / 86400000);
  return [0, 1, 2].map((i) => DEED_SUGGESTIONS[(dayIndex + i * 5) % DEED_SUGGESTIONS.length]);
}

